const toKey = (date: Date | string): string =>
  typeof date === 'string' ? date.slice(0, 10) : format(date, 'yyyy-MM-dd');

/** 공휴일이면 이름을, 아니면 null을 반환한다 */
export function getHolidayName(date: Date | string): string | null {
  return HOLIDAYS[toKey(date)] ?? null;
}

/** 법정 공휴일 여부 (일·토요일은 포함하지 않는다 — 요일 색은 별도 처리) */
export function isKoreanHoliday(date: Date | string): boolean {
  return toKey(date) in HOLIDAYS;
}
